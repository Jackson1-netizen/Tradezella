export function attachApexBook(state: JournalState): JournalState {
  if (state.trades.some((trade) => trade.id.startsWith("stdqa-"))) return state
  const empty = [...state.accounts].reverse().find((account) => account.size === 50000 && !state.trades.some((trade) => trade.accountId === account.id))
  const id = empty?.id ?? APEX_ACCOUNT_ID
  const accounts = empty
    ? state.accounts.map((account) => account.id === id
      ? { ...account, broker: "STDQA2026101600541", maxDrawdown: 2000, drawdownType: "Trailing" as const, maxDailyLoss: 0, profitTarget: account.profitTarget || 3000 }
      : account)
    : [...state.accounts, apexAccount(id)]
  return {
    ...state,
    accounts,
    trades: [...state.trades, ...apexTrades(id)],
    filters: { ...state.filters, accountId: id, range: "all", symbol: "" },
  }
}
